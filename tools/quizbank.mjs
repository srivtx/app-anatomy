// Builds lib/quizbank.js: every "predict first" question in the chapters, plus questions generated
// from the course data (what the big runs found vs what is still open, what works vs what's a trap,
// and which chapter teaches a given idea). Run: node tools/quizbank.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import { ALL } from "../lib/catalog.js";

const live = new Map(ALL.filter((c) => c.live).map((c) => [c.id, c]));
const questions = [];
const hash = (s) => { let x = 2166136261; for (const ch of s) x = Math.imul(x ^ ch.charCodeAt(0), 16777619); return (x >>> 0).toString(36); };
const add = (q) => { q.id = hash(q.kind + q.ch + q.q + q.options.join("|")); if (!questions.some((o) => o.id === q.id)) questions.push(q); };

// 1. predict({...}) blocks, cut out of the chapter source and evaluated on their own
function objectAt(src, start) {
  let depth = 0, i = start, str = null;
  for (; i < src.length; i++) {
    const c = src[i];
    if (str) { if (c === "\\") { i++; continue; } if (c === str) str = null; continue; }
    if (c === '"' || c === "'" || c === "`") { str = c; continue; }
    if (c === "{") depth++;
    if (c === "}") { depth--; if (!depth) return src.slice(start, i + 1); }
  }
  return null;
}
let failed = 0;
for (const f of readdirSync(new URL("../chapters/", import.meta.url))) {
  const ch = f.replace(/\.js$/, "");
  if (!live.has(ch)) continue;
  const src = readFileSync(new URL(`../chapters/${f}`, import.meta.url), "utf8");
  for (let at = src.indexOf("predict({"); at >= 0; at = src.indexOf("predict({", at + 9)) {
    const text = objectAt(src, at + 8);
    if (!text) continue;
    try {
      const o = vm.runInNewContext(`(${text.replace(/chapter:\s*id\b/, "chapter: null")})`, {}, { timeout: 50 });
      if (typeof o.question !== "string" || !Array.isArray(o.options) || typeof o.answer !== "number") throw new Error("shape");
      if (/\b(the|this) (curve|chart|plot|graph|figure) (above|below)|\bshown (above|below)/i.test(o.question)) continue;   // needs the chapter's picture
      add({ kind: "predict", ch, q: o.question, options: o.options.map(String), answer: o.answer, explain: String(o.explain || "") });
    } catch { failed++; }
  }
}

// 2. which chapter teaches this? (the blurb, four chapter titles from the same level or nearby)
const all = [...live.values()];
all.forEach((c, i) => {
  const others = all.filter((o) => o.id !== c.id && Math.abs(all.indexOf(o) - i) <= 12);
  const pick = []; for (let k = 0; pick.length < 3 && k < others.length; k++) { const o = others[(i * 7 + k * 5) % others.length]; if (!pick.includes(o)) pick.push(o); }
  if (pick.length < 3) return;
  const pos = i % 4, opts = pick.map((o) => o.title); opts.splice(pos, 0, c.title);
  add({ kind: "where", ch: c.id, q: `Which chapter is this? “${c.blurb}”`, options: opts, answer: pos, explain: `<p>That's <b>${c.title}</b> (chapter ${c.n}).</p>` });
});

// 3. course data, when this course has it
const extra = await Promise.allSettled([import("../lib/known.js"), import("../lib/practice.js")]);
if (extra[0].status === "fulfilled") {
  const { KNOWN = {}, OPEN = {} } = extra[0].value;
  for (const [ch, list] of Object.entries(KNOWN)) if (live.has(ch)) list.forEach((t) =>
    add({ kind: "settled", ch, q: `Settled result or open question? “${t}”`, options: ["A settled result: a big published run found it", "Still an open question"], answer: 0, explain: `<p>Settled: it's listed under <i>What the big runs found</i> in ${live.get(ch).title}.</p>` }));
  for (const [ch, list] of Object.entries(OPEN)) if (live.has(ch)) list.forEach((t) =>
    add({ kind: "settled", ch, q: `Settled result or open question? “${t}”`, options: ["A settled result: a big published run found it", "Still an open question"], answer: 1, explain: `<p>Open: it's listed under <i>Still unknown</i> in ${live.get(ch).title}.</p>` }));
}
if (extra[1].status === "fulfilled") {
  const { PRACTICE = {} } = extra[1].value;
  for (const [ch, p] of Object.entries(PRACTICE)) if (live.has(ch)) {
    (p.works || []).forEach((t) => add({ kind: "field", ch, q: `From the field: good practice, or a trap? “${t}”`, options: ["Good practice: it usually works", "A trap that bites people"], answer: 0, explain: `<p>Good practice, from the field notes of ${live.get(ch).title}.</p>` }));
    (p.traps || []).forEach((t) => add({ kind: "field", ch, q: `From the field: good practice, or a trap? “${t}”`, options: ["Good practice: it usually works", "A trap that bites people"], answer: 1, explain: `<p>A trap, from the field notes of ${live.get(ch).title}.</p>` }));
  }
}

const kinds = {}; for (const q of questions) kinds[q.kind] = (kinds[q.kind] || 0) + 1;
writeFileSync(new URL("../lib/quizbank.js", import.meta.url),
  `// Generated by tools/quizbank.mjs from the chapters and course data. Don't edit by hand.\nexport const BANK = ${JSON.stringify(questions)};\n`);
console.log(`${questions.length} questions`, kinds, failed ? `(${failed} predict blocks skipped)` : "");
